# Description:
# ----------------------------------------------------------------------------------------------------------------------
# When each instrument's exchange session ends, and whether it is in its final minutes right now.
#
# WHY THIS EXISTS (user 2026-09-06): "the auto close may be best in the last 30 minutes of trading for the instrument as
# we should have seen the relative volume and close before the market is unavailable until following day / week".
#
# RVOL, VolumeScore, above-VWAP and ATR all describe the BREAK bar, and a daily break bar is not complete until its
# market closes -- but once it has closed the position cannot be traded until the next session, or Monday. The last half
# hour is the only window where the day's volume is substantially known AND the position can still be acted on.
#
# ----------------------------------------------------------------------------------------------------------------------
# EVERY TIME IN THIS MODULE IS DERIVED, NONE IS REMEMBERED.
# ----------------------------------------------------------------------------------------------------------------------
# The first version of this file was written from assumption and was wrong: it put the ASX close at 16:00 (measured
# 16:12), Hong Kong at 16:00 (measured 16:10), and omitted Tokyo, bonds, commodities and indices entirely -- 205
# instruments that would have fallen through to "never closing" with nothing to distinguish that from a deliberate
# exemption. So the table is now GENERATED (`market_hours_data.py`) from the exchange's own record and regenerated by
# `python market_hours.py --refresh`; `--check` fails if it has drifted, the same contract build_data_dictionary uses.
#
# THE SOURCE is Yahoo's `history_metadata.currentTradingPeriod.regular` -- the exchange timezone plus the session's
# start and end for the instrument itself. IG was tried first and REJECTED, measured 2026-09-07: `/markets/{epic}`
# carries an `openingHours` field, but it is null on 12 of the 14 markets that hold epics, and where it is populated
# (US 24-hour share CFDs) it describes IG's own dealing window -- AAPL reports 00:00-23:59 -- not the cash session whose
# close completes the bar. Confirmed identical across API versions 1, 2 and 3.
#
# KEYED BY EXCHANGE, NOT BY MARKET, because the scanner's "market" is an index membership and several of them span
# exchanges that close at different times. Measured across the live universe:
#   * "Euronext" is SEVEN exchanges -- Paris, Amsterdam, Milan, Brussels, Oslo, Lisbon, Dublin.
#   * "Indices" is twenty-three, each following its own underlying: ^GSPC New York, ^FTSE London, ^N225 Tokyo,
#     ^HSI Hong Kong, ^GDAXI Frankfurt.
#   * "Government Bonds" is US-listed ETFs plus four London-listed gilt funds.
# A market-level table cannot express any of that, and averaging it would be a guess wearing a measurement's clothes.
#
# THE LOCAL TIME IS STORED, THE UTC TIME IS DERIVED. London, New York, Frankfurt and Sydney all observe daylight
# saving, on different dates, and Sydney moves the opposite way. A stored UTC close is right for part of the year and
# silently wrong for the rest -- and "wrong" here means running the check after the market has gone, when nothing can be
# done about what it finds.
#
# CONTINUOUS MARKETS are derived, not declared: a session reported as 00:00-23:59 has no closing bar to wait for and no
# last-30-minutes to be in. FX, commodity futures and crypto all report exactly that. `in_closing_window` returns False
# for them, and the caller must read that as "never in the window" rather than as an error -- so the auto-closer never
# acts on them. That is a real limit of scope, stated rather than hidden.
#
# NOT MODELLED: public holidays, half-days, and the lunch breaks at Tokyo, Hong Kong and the mainland Chinese
# exchanges. On a holiday or half-day this reports a window that has already passed or has not arrived, and the caller
# finds nothing tradeable and does nothing. That fails safe. `is_tradeable_now()` exists for the caller that wants the
# authoritative answer instead: IG's own marketStatus for the epic, which is what actually governs whether a position
# can be closed, holidays included.
#
# Usage:  python market_hours.py --check      # fail if the generated table has drifted or misses the universe
#         python market_hours.py --refresh    # regenerate market_hours_data.py from the exchanges
#         python market_hours.py --show       # print the table with each entry's provenance
# ======================================================================================================================

import datetime as _dt
import logging
import re as _re

log = logging.getLogger("market_hours")

try:
    from zoneinfo import ZoneInfo
except ImportError:                                     # pragma: no cover - Python < 3.9
    ZoneInfo = None

# The window the auto-closer acts in. 30 minutes is the user's own figure (2026-09-06).
CLOSING_WINDOW_MINUTES = 30

# A session covering the whole clock has no close to wait for. Yahoo reports these as 00:00-23:59.
_CONTINUOUS_OPEN, _CONTINUOUS_CLOSE = "00:00", "23:59"


# ----------------------------------------------------------------------------------------------------------------------
# Resolving an instrument to the exchange that sets its hours
# ----------------------------------------------------------------------------------------------------------------------
def yahoo_symbol(ticker: str) -> str:
    """The Yahoo symbol for a universe ticker.

    The universe carries synthetic names for indices, commodities, FX and crypto (XAUUSD, SPX500, UK100), which do not
    resolve at Yahoo at all -- and some of them collide with unrelated real listings, so a naive lookup silently
    returns the wrong instrument's hours. `OIL` is a US-listed ETN and `NASDAQ` is a bank holding company; both answer
    with New York hours for what are meant to be a futures contract and an index. config.YAHOO_MAP is the project's
    existing answer to this and is used here rather than a second one.
    """
    try:
        import config
        return (getattr(config, "YAHOO_MAP", {}) or {}).get(ticker) or ticker
    except Exception:
        return ticker


def exchange_key(ticker: str) -> str:
    """Which hours-setting exchange this instrument belongs to.

    Yahoo encodes the listing venue in the symbol suffix, so the suffix IS the exchange for every equity. Indices carry
    no suffix and each follows its own underlying market, so they are keyed individually.
    """
    y = str(yahoo_symbol(ticker) or "")
    if y.startswith("^"):
        return "INDEX:" + y
    if y.endswith("-USD"):
        return "SUFFIX:-USD"
    m = _re.search(r"(=[A-Z]|\.[A-Za-z]+)$", y)
    return "SUFFIX:" + m.group(1) if m else "SUFFIX:(bare)"


def session(ticker: str):
    """{tz, open, close, ...} for this instrument's exchange, or None if the exchange is not in the table."""
    from market_hours_data import EXCHANGES
    return EXCHANGES.get(exchange_key(ticker))


def is_continuous(ticker: str) -> bool:
    """Does this instrument trade around the clock, with no closing bar to wait for?"""
    s = session(ticker)
    return bool(s) and s["open"] == _CONTINUOUS_OPEN and s["close"] == _CONTINUOUS_CLOSE


def close_utc(ticker: str, on_day: _dt.date):
    """The UTC datetime this instrument's exchange closes on `on_day`, or None if it has no close.

    Derived from the stored LOCAL close through the exchange's own timezone, so it follows daylight saving in both
    directions without anyone remembering to change it twice a year.
    """
    s = session(ticker)
    if not s or ZoneInfo is None or is_continuous(ticker):
        return None
    hh, mm = (int(x) for x in s["close"].split(":"))
    local = _dt.datetime.combine(on_day, _dt.time(hh, mm), tzinfo=ZoneInfo(s["tz"]))
    return local.astimezone(_dt.timezone.utc)


def in_closing_window(ticker: str, now=None, minutes: int = CLOSING_WINDOW_MINUTES) -> bool:
    """Is this instrument inside the final `minutes` of its session right now?

    True from (close - minutes) up to the close itself, and False after it: once the market has gone the position
    cannot be traded and there is nothing this window is for. False for a continuous instrument and for one whose
    exchange is not in the table -- both mean "do not act", which is the safe direction.

    The day is taken in the EXCHANGE's timezone, not UTC. Sydney closes at 06:12 UTC, so a UTC date would be right
    there by luck; Auckland or a late US session would not be, and a rule that only holds for some longitudes is not
    a rule.
    """
    s = session(ticker)
    if not s or ZoneInfo is None or is_continuous(ticker):
        return False
    now = now or _dt.datetime.now(_dt.timezone.utc)
    if now.tzinfo is None:
        now = now.replace(tzinfo=_dt.timezone.utc)
    local_day = now.astimezone(ZoneInfo(s["tz"])).date()
    closes = close_utc(ticker, local_day)
    if closes is None:
        return False
    return (closes - _dt.timedelta(minutes=minutes)) <= now <= closes


def session_fraction_elapsed(ticker: str, now=None):
    """How much of today's session has passed, 0.0-1.0, or None where unknown.

    Used to say HOW COMPLETE a partial bar is, so a reading taken before the close is reported with its own limitation
    rather than presented as final. Assumes a continuous session between open and close; the exchanges with a lunch
    break (Tokyo, Hong Kong, Shanghai, Shenzhen) therefore read slightly high. That is stated rather than corrected --
    an approximate completeness figure honest about being approximate beats a precise one nobody can check.
    """
    s = session(ticker)
    if not s or ZoneInfo is None or is_continuous(ticker):
        return None
    now = now or _dt.datetime.now(_dt.timezone.utc)
    if now.tzinfo is None:
        now = now.replace(tzinfo=_dt.timezone.utc)
    tz = ZoneInfo(s["tz"])
    local_now = now.astimezone(tz)
    def _at(hhmm):
        hh, mm = (int(x) for x in hhmm.split(":"))
        return _dt.datetime.combine(local_now.date(), _dt.time(hh, mm), tzinfo=tz)
    opens, closes = _at(s["open"]), _at(s["close"])
    span = (closes - opens).total_seconds()
    if span <= 0:
        return None
    return max(0.0, min(1.0, (local_now - opens).total_seconds() / span))


def volume_projection_factor(ticker: str):
    """Divide a closing-window volume by this to project the full session. None where unknown.

    The 5th-percentile share, so the projection reads HIGH in ~95% of sessions and an unfinished bar can
    never be the reason a position is closed. Measured 2026-09-07 over 910 verdict comparisons: applying
    this took false closes from 1.98% of cases to 1.21%, turning them into false KEEPS -- which cost
    nothing, because leaving a position open is the status quo.

    Returns None when the exchange has no measured share, and the caller must treat that as "cannot judge"
    rather than as a factor of 1.0: assuming completeness is exactly the error this exists to prevent.
    """
    s = session(ticker)
    if not s or is_continuous(ticker):
        return None
    return s.get("vol_share_p05")


def unjudgeable_exchanges() -> dict:
    """{exchange_key: reason} for venues with a close but no measurable volume — mostly indices.

    An index has no traded volume of its own, so RVOL and VolumeScore cannot be computed for it and the
    closing-window correction has nothing to scale. Instruments there are left alone, which is safe; the
    danger is that "left alone" is indistinguishable from "passed" unless it is stated somewhere, so this
    is what the daily generated-table audit reports.
    """
    from market_hours_data import EXCHANGES
    return {k: e.get("vol_share_reason") or "no volume-completion share recorded"
            for k, e in EXCHANGES.items()
            if (e["open"], e["close"]) != (_CONTINUOUS_OPEN, _CONTINUOUS_CLOSE)
            and not e.get("vol_share_p05")}


def unjudgeable_instruments(tickers) -> list:
    """Which of `tickers` cannot be volume-judged in a closing window, and therefore never auto-closed."""
    bad = set(unjudgeable_exchanges())
    return sorted({t for t in (tickers or []) if exchange_key(t) in bad})


def unmapped(tickers) -> list:
    """Which of `tickers` resolve to no exchange at all — the check that stops a silent gap reappearing.

    An unmapped instrument is indistinguishable from a continuous one at the call site: both are "never in a closing
    window". The absence of this check is why 205 instruments went missing from the first version unnoticed.
    """
    return sorted({t for t in (tickers or []) if session(t) is None})


def is_tradeable_now(epic: str, session_obj=None) -> bool:
    """Does IG say this epic can be dealt right now?

    The authoritative answer to the only question that matters at the moment of closing, and the one thing the derived
    table cannot supply: it covers holidays, half-days and IG's own suspensions without modelling any of them.
    Measured 2026-09-07 12:57 UTC on a Monday -- London TRADEABLE, Sydney/Tokyo/Hong Kong EDITS_ONLY (closed), New York
    EDITS_ONLY (pre-open) -- so the field tracks real session state rather than a static flag.

    Returns False on any error: an unanswerable question about a real position is a reason not to act.
    """
    try:
        import ig_shim
        s = session_obj or ig_shim.session_for()
        if s is None:
            return False
        snap = (s.get(f"/markets/{epic}", version="3") or {}).get("snapshot") or {}
        return str(snap.get("marketStatus") or "").upper() == "TRADEABLE"
    except Exception as exc:
        log.warning("could not read marketStatus for %s: %s", epic, exc)
        return False


# ----------------------------------------------------------------------------------------------------------------------
# Generation — the only place a time enters this module
# ----------------------------------------------------------------------------------------------------------------------
def _universe_tickers():
    """Every ticker the scanner covers, from the live universe rather than a copy of it."""
    import run_hvf_report
    return [t for tickers in run_hvf_report.UNIVERSE.values() for t in tickers]


def probe(ticker: str):
    """Ask the exchange, through Yahoo, for this instrument's session. (tz, open, close) or None.

    Only the LOCAL times are kept. The reported period is not always today's -- pre-open on a Monday, AAPL still
    reports the previous Friday -- so the date is deliberately discarded and the time-of-day re-projected onto
    whichever day is being asked about.
    """
    import yfinance as yf
    md = yf.Ticker(yahoo_symbol(ticker)).history_metadata or {}
    tz = md.get("exchangeTimezoneName")
    reg = (md.get("currentTradingPeriod") or {}).get("regular") or {}
    start, end = reg.get("start"), reg.get("end")
    if not (tz and start and end and ZoneInfo):
        return None
    z = ZoneInfo(tz)
    ls = _dt.datetime.fromtimestamp(start, _dt.timezone.utc).astimezone(z)
    le = _dt.datetime.fromtimestamp(end, _dt.timezone.utc).astimezone(z)
    return (tz, ls.strftime("%H:%M"), le.strftime("%H:%M"))


def volume_share(ticker: str, minutes: int = CLOSING_WINDOW_MINUTES, period: str = "1mo"):
    """What fraction of a session's volume has traded `minutes` before the close? (median, p05, n).

    A bar read inside the closing window is unfinished, so its volume -- and therefore RVOL and
    VolumeScore -- is understated, and understating volume makes a test FAIL, which makes the closer
    CLOSE. The bias runs toward selling a sound position, so it has to be corrected rather than tolerated.

    p05 is what the correction divides by, not the median. Dividing by the 5th percentile OVER-states the
    projected full-day volume in ~95% of sessions, so the reading errs high, the test errs toward passing,
    and an unfinished bar can never be the reason a position is closed. Measured 2026-09-07 over 472
    sessions: median 0.864 overall, but ASX 0.593 -- its closing auction is a large share of the day, and
    a single global constant would be badly wrong for it. Hence per exchange.
    """
    import datetime as _d
    import yfinance as yf
    s = session(ticker)
    if not s or is_continuous(ticker) or ZoneInfo is None:
        return None
    tz = ZoneInfo(s["tz"])
    hh, mm = (int(x) for x in s["close"].split(":"))
    df = yf.Ticker(yahoo_symbol(ticker)).history(period=period, interval="5m")
    if df is None or df.empty:
        return None
    df = df.tz_convert(tz)
    shares = []
    for day, chunk in df.groupby(df.index.date):
        total = float(chunk["Volume"].sum())
        if total <= 0 or len(chunk) < 10:
            continue
        cutoff = _d.datetime.combine(day, _dt.time(hh, mm), tzinfo=tz) - _dt.timedelta(minutes=minutes)
        shares.append(float(chunk[chunk.index < cutoff]["Volume"].sum()) / total)
    if len(shares) < 5:
        return None
    shares.sort()
    return (shares[len(shares) // 2], shares[int(0.05 * len(shares))], len(shares))


def derive(samples_per_exchange: int = 3, tickers=None, pause: float = 0.15, share_keys=None):
    """Derive the whole table from the exchanges. {exchange_key: entry} plus a list of failures.

    Several tickers are sampled per exchange and required to AGREE. A split is reported rather than resolved by
    majority: two closing times inside one exchange key means the key is wrong, and quietly taking the more popular
    one would bury exactly the kind of mistake this module exists to stop.
    """
    import collections
    import time
    by_key = collections.OrderedDict()
    for t in (tickers if tickers is not None else _universe_tickers()):
        by_key.setdefault(exchange_key(t), []).append(t)
    table, problems = {}, []
    for key, members in by_key.items():
        seen, used = collections.Counter(), []
        for t in members[:samples_per_exchange]:
            try:
                got = probe(t)
            except Exception as exc:
                log.debug("probe failed for %s: %s", t, exc)
                got = None
            if got:
                seen[got] += 1
                used.append(t)
            time.sleep(pause)
        if not seen:
            problems.append(f"{key}: no sample answered (tried {members[:samples_per_exchange]})")
            continue
        if len(seen) > 1:
            problems.append(f"{key}: samples DISAGREE {dict(seen)}")
            continue
        (tz, op, cl), n = seen.most_common(1)[0]
        entry = {"tz": tz, "open": op, "close": cl, "samples": used, "agreement": f"{n}/{len(used)}"}
        # The closing-window volume share, for the exchanges that HAVE a closing window. Derived from the
        # same instruments the hours came from, so the two cannot describe different venues.
        if (op, cl) != (_CONTINUOUS_OPEN, _CONTINUOUS_CLOSE) and (share_keys is None or key in share_keys):
            got = []
            for t in used:
                try:
                    v = volume_share(t)
                except Exception as exc:
                    # WARNING, not debug. This was debug, and it hid the reason every exchange came back
                    # without a share on one run -- the failure looked identical to "this venue reports no
                    # volume", which is a legitimate state, so a real error was indistinguishable from an
                    # expected absence.
                    log.warning("volume share failed for %s: %s: %s", t, type(exc).__name__, exc)
                    v = None
                if v:
                    got.append(v)
                time.sleep(pause)
            if got:
                entry["vol_share_median"] = round(sum(g[0] for g in got) / len(got), 3)
                # The LOWEST p05 across the sampled instruments -- the most conservative of them, because
                # the correction must not under-project for any member of the exchange.
                entry["vol_share_p05"] = round(min(g[1] for g in got), 3)
                entry["vol_share_sessions"] = sum(g[2] for g in got)
            else:
                # NOT FATAL (user 2026-09-07: "progress with all the auto-close actions that you could
                # rather than stall on missing data for some", and "if there is no volume information
                # returned for a subset of data then these cannot be judged. A warning should be
                # available in the system logs to highlight this").
                #
                # Refusing to write the whole table because some exchanges lack volume was the same
                # stalling error: it blocked the closing-window correction for the 1,700+ instruments
                # that CAN be judged in order to protect the handful that cannot. The absence is recorded
                # against the exchange instead, unjudgeable_exchanges() reports it, and the daily
                # generated-table audit raises it. Indices are the normal case -- an index has no traded
                # volume of its own -- so this is expected, not a fault, but it must be VISIBLE rather
                # than inferred from a blank.
                entry["vol_share_p05"] = None
                entry["vol_share_reason"] = "no traded volume reported for this exchange"
                log.warning("%s: no volume-share sample answered; instruments there cannot be "
                            "volume-judged in the closing window", key)
        table[key] = entry
    return table, problems


_HEADER = '''# ======================================================================================================================
# File:         market_hours_data.py
# ----------------------------------------------------------------------------------------------------------------------
# GENERATED FILE - DO NOT EDIT BY HAND. Regenerate with `python market_hours.py --refresh`.
#
# Each exchange's regular session, derived from Yahoo's own `currentTradingPeriod.regular` for the sampled instruments
# named beside it. Times are LOCAL to the exchange; the UTC close is computed through `tz` so daylight saving follows
# automatically. A session of 00:00-23:59 means the venue trades continuously and has no closing bar.
#
# Generated: {when}
# Source:    yfinance history_metadata.currentTradingPeriod.regular
# Universe:  run_hvf_report.UNIVERSE ({n_tickers} tickers, {n_keys} exchanges)
# ======================================================================================================================

EXCHANGES = {{
{body}}}
'''


def write_module(table, path="market_hours_data.py"):
    # Driven by one field list rather than a hand-written f-string. The f-string named five fields, so when
    # the volume-completion shares were added the generator derived them and the WRITER SILENTLY DROPPED
    # them -- the table looked complete and every exchange read as having no volume, which would have
    # disabled the closing correction for 1,711 instruments without anything reporting a fault.
    order = ("tz", "open", "close", "vol_share_median", "vol_share_p05", "vol_share_sessions",
             "vol_share_reason", "samples", "agreement")
    lines = []
    for key in sorted(table):
        e = table[key]
        unknown = set(e) - set(order)
        assert not unknown, f"{key} carries fields the writer would drop: {sorted(unknown)}"
        body = ", ".join(f'"{k}": {e[k]!r}' for k in order if k in e)
        lines.append(f"    {key!r}: {{{body}}},\n")
    text = _HEADER.format(when=_dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
                          n_tickers=len(_universe_tickers()), n_keys=len(table), body="".join(lines))
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return path


if __name__ == "__main__":
    import argparse
    import sys
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
    ap = argparse.ArgumentParser(description="Exchange sessions, derived from the exchanges themselves.")
    ap.add_argument("--refresh", action="store_true", help="regenerate market_hours_data.py")
    ap.add_argument("--check", action="store_true", help="fail if the table misses any of the live universe")
    ap.add_argument("--show", action="store_true", help="print the table with provenance")
    ap.add_argument("--samples", type=int, default=3, help="instruments sampled per exchange (default 3)")
    ap.add_argument("--shares", choices=("epics", "all", "none"), default="epics",
                    help="which exchanges get a volume-completion share measured (default: those with IG epics)")
    a = ap.parse_args()

    if a.refresh:
        keys = None
        if a.shares == "none":
            keys = set()
        elif a.shares == "epics":
            try:
                from db_pool import get_db
                _db = get_db()
                try:
                    rows = _db.run("select ticker from epic_lookup where epic is not null") or []
                finally:
                    _db.close()
                keys = {exchange_key(r[0]) for r in rows}
                log.info("measuring volume shares for %d exchange(s) that carry IG epics", len(keys))
            except Exception as exc:
                log.warning("could not read epic_lookup (%s); measuring every exchange", exc)
                keys = None
        table, problems = derive(samples_per_exchange=a.samples, share_keys=keys)
        for p in problems:
            log.error("%s", p)
        if problems:
            print(f"REFUSING to write: {len(problems)} exchange(s) unresolved or split.")
            raise SystemExit(1)
        print("wrote", write_module(table), f"({len(table)} exchanges)")
        raise SystemExit(0)

    if a.show:
        from market_hours_data import EXCHANGES
        for k in sorted(EXCHANGES):
            e = EXCHANGES[k]
            tag = " CONTINUOUS" if (e["open"], e["close"]) == (_CONTINUOUS_OPEN, _CONTINUOUS_CLOSE) else ""
            print(f'{k:22s} {e["tz"]:20s} {e["open"]}-{e["close"]}  {e["agreement"]:5s} {e["samples"]}{tag}')
        raise SystemExit(0)

    if a.check:
        missing = unmapped(_universe_tickers())
        if missing:
            print(f"{len(missing)} instrument(s) map to NO exchange, e.g. {missing[:10]}")
            print("Run: python market_hours.py --refresh")
            raise SystemExit(1)
        print(f"OK: every one of {len(_universe_tickers())} universe instruments resolves to an exchange.")
        raise SystemExit(0)

    ap.print_help()
    sys.exit(2)
